"""Report configuration for Hazsight PDF generation.

Modular + parameterized — pass a custom ReportConfig to change the report's
appearance without modifying the generator code. All colors, fonts, text,
and layout settings are configurable.
"""

from dataclasses import dataclass, field
from pathlib import Path
from typing import Dict, Optional, Tuple


@dataclass
class ReportConfig:
    """Configuration for PDF report generation.

    All fields have sensible defaults matching the Hazsight brand
    (NVIDIA-green on dark, monospace tech readout style). Override
    any field to customize.

    Example:
        config = ReportConfig(
            title="Custom Safety Report",
            brand_color=(0, 100, 200),  # custom blue
        )
        pdf_bytes = generate_report(analysis, image, config)
    """

    # --- Report metadata ---
    title: str = "Safety Audit Report"
    subtitle: str = "Hazsight — AI Safety Inspector"
    organization: str = "Team DAMR58H"
    hackathon: str = "Nebius x NVIDIA Global AI Hackathon"
    track: str = "Best Apps & Agents"

    # --- Color scheme (R, G, B tuples 0-255) ---
    # Severity colors — used for bounding boxes, table rows, score display
    severity_colors: Dict[str, Tuple[int, int, int]] = field(
        default_factory=lambda: {
            "CRITICAL": (239, 68, 68),  # red-500
            "HIGH": (249, 115, 22),  # orange-500
            "MEDIUM": (250, 204, 21),  # amber-400
            "LOW": (16, 185, 129),  # emerald-500
        }
    )

    # Brand color (NVIDIA green #76b900)
    brand_color: Tuple[int, int, int] = (118, 185, 0)

    # Text colors
    text_primary: Tuple[int, int, int] = (30, 30, 30)  # near-black
    text_secondary: Tuple[int, int, int] = (100, 100, 100)  # gray
    text_muted: Tuple[int, int, int] = (150, 150, 150)  # light gray

    # Background colors
    bg_white: Tuple[int, int, int] = (255, 255, 255)
    bg_light: Tuple[int, int, int] = (245, 245, 245)
    bg_card: Tuple[int, int, int] = (250, 250, 250)

    # --- Fonts ---
    font_family: str = "Helvetica"
    font_bold: str = "Helvetica-Bold"
    font_mono: str = "Courier"
    font_mono_bold: str = "Courier-Bold"

    # Font sizes (points)
    size_h1: int = 24
    size_h2: int = 16
    size_h3: int = 12
    size_body: int = 10
    size_small: int = 8
    size_tiny: int = 6

    # --- Page settings ---
    page_size: str = "A4"  # "A4" or "letter"
    margin_top: float = 50
    margin_bottom: float = 50
    margin_left: float = 50
    margin_right: float = 50

    # --- Layout ---
    image_max_width: float = 450  # points
    image_max_height: float = 300  # points
    table_col_widths: Tuple[float, ...] = (
        80,
        60,
        180,
        120,
        50,
    )  # category, severity, description, recommendation, confidence

    # --- Logo (optional — path to image file) ---
    logo_path: Optional[Path] = None
    logo_width: float = 30  # points

    # --- Footer ---
    footer_text: str = (
        "Generated by Hazsight — NVIDIA Nemotron on Nebius Token Factory"
    )
    footer_size: int = 7

    # --- Include sections (toggle what to include) ---
    include_scene_description: bool = True
    include_safety_score: bool = True
    include_annotated_image: bool = True
    include_hazard_table: bool = True
    include_regulations: bool = True  # Tavily citations (if available)
    include_timestamp: bool = True


def default_config() -> ReportConfig:
    """Get the default report configuration."""
    return ReportConfig()
